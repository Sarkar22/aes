"""
AES block cipher — software reference model
Supports 128-, 192-, and 256-bit keys (FIPS 197).

State layout: column-major, 16 bytes.
  byte index = col*4 + row  →  byte 0 = (row0,col0), byte 15 = (row3,col3)
This matches the pipelined RTL implementation exactly.

Decryption uses the direct inverse cipher (FIPS 197 §5.3), mirroring the
RTL's aes_inv_round order: InvShiftRows → InvSubBytes → AddRoundKey → InvMixColumns.
"""

# ---------------------------------------------------------------------------
# GF(2^8) arithmetic  (irreducible poly x^8+x^4+x^3+x+1, i.e. 0x11b)
# ---------------------------------------------------------------------------

def _xtime(a):
    return ((a << 1) ^ 0x1B) & 0xFF if (a & 0x80) else (a << 1)

def _gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        a = _xtime(a)
        b >>= 1
    return p

