# ---------------------------------------------------------------------------
# Key expansion  (FIPS 197 §5.2)
# ---------------------------------------------------------------------------

_RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36]

def _sub_word(w):
    return (_SBOX[(w >> 24) & 0xFF] << 24 | _SBOX[(w >> 16) & 0xFF] << 16 |
            _SBOX[(w >>  8) & 0xFF] <<  8 | _SBOX[ w        & 0xFF])

def _rot_word(w):
    return ((w << 8) | (w >> 24)) & 0xFFFFFFFF

def _key_expand(key: bytes):
    """Return list of Nr+1 round keys, each a 128-bit int (big-endian word order)."""
    n = len(key)
    if   n == 16: Nk, Nr = 4, 10
    elif n == 24: Nk, Nr = 6, 12
    elif n == 32: Nk, Nr = 8, 14
    else: raise ValueError(f"key must be 16, 24, or 32 bytes, got {n}")

    w = [int.from_bytes(key[i*4:i*4+4], 'big') for i in range(Nk)]
    for i in range(Nk, 4*(Nr+1)):
        t = w[i-1]
        if i % Nk == 0:
            t = _sub_word(_rot_word(t)) ^ (_RCON[i//Nk - 1] << 24)
        elif Nk == 8 and i % Nk == 4:
            t = _sub_word(t)
        w.append((w[i-Nk] ^ t) & 0xFFFFFFFF)

    return [w[4*r]<<96 | w[4*r+1]<<64 | w[4*r+2]<<32 | w[4*r+3]
            for r in range(Nr+1)]

# ---------------------------------------------------------------------------
# State helpers  (column-major: index = col*4 + row)
# ---------------------------------------------------------------------------

def _ark(s, rk):
    rb = rk.to_bytes(16, 'big')
    return [s[i] ^ rb[i] for i in range(16)]

# ---------------------------------------------------------------------------
# Forward round operations
# ---------------------------------------------------------------------------

def _sub_bytes(s):
    return [_SBOX[b] for b in s]

def _shift_rows(s):
    # row r shifts left by r positions across columns
    out = [0]*16
    for r in range(4):
        for c in range(4):
            out[c*4+r] = s[((c+r) & 3)*4+r]
    return out

def _mix_col(col):
    a0,a1,a2,a3 = col
    return [
        _gmul(a0,2)^_gmul(a1,3)^a2        ^a3,
        a0        ^_gmul(a1,2)^_gmul(a2,3)^a3,
        a0        ^a1         ^_gmul(a2,2)^_gmul(a3,3),
        _gmul(a0,3)^a1        ^a2         ^_gmul(a3,2),
    ]

def _mix_columns(s):
    out = [0]*16
    for c in range(4):
        m = _mix_col([s[c*4+r] for r in range(4)])
        for r in range(4): out[c*4+r] = m[r]
    return out

# ---------------------------------------------------------------------------
# Inverse round operations  (direct inverse cipher order)
# ---------------------------------------------------------------------------

def _inv_sub_bytes(s):
    return [_SBOX_INV[b] for b in s]

def _inv_shift_rows(s):
    # row r shifts right by r positions (i.e. left by 4-r)
    out = [0]*16
    for r in range(4):
        for c in range(4):
            out[c*4+r] = s[((c-r) & 3)*4+r]
    return out

def _inv_mix_col(col):
    a0,a1,a2,a3 = col
    return [
        _gmul(a0,14)^_gmul(a1,11)^_gmul(a2,13)^_gmul(a3, 9),
        _gmul(a0, 9)^_gmul(a1,14)^_gmul(a2,11)^_gmul(a3,13),
        _gmul(a0,13)^_gmul(a1, 9)^_gmul(a2,14)^_gmul(a3,11),
        _gmul(a0,11)^_gmul(a1,13)^_gmul(a2, 9)^_gmul(a3,14),
    ]

def _inv_mix_columns(s):
    out = [0]*16
    for c in range(4):
        m = _inv_mix_col([s[c*4+r] for r in range(4)])
        for r in range(4): out[c*4+r] = m[r]
    return out

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def encrypt(plaintext: bytes, key: bytes) -> bytes:
    """Encrypt one 16-byte block."""
    assert len(plaintext) == 16, "block must be 16 bytes"
    rks = _key_expand(key)
    Nr  = len(rks) - 1
    s   = list(plaintext)
    s   = _ark(s, rks[0])
    for r in range(1, Nr):
        s = _sub_bytes(s)
        s = _shift_rows(s)
        s = _mix_columns(s)
        s = _ark(s, rks[r])
    s = _sub_bytes(s)
    s = _shift_rows(s)
    s = _ark(s, rks[Nr])
    return bytes(s)

def decrypt(ciphertext: bytes, key: bytes) -> bytes:
    """Decrypt one 16-byte block (direct inverse cipher, FIPS 197 §5.3)."""
    assert len(ciphertext) == 16, "block must be 16 bytes"
    rks = _key_expand(key)
    Nr  = len(rks) - 1
    s   = list(ciphertext)
    s   = _ark(s, rks[Nr])
    for r in range(Nr-1, 0, -1):
        s = _inv_shift_rows(s)
        s = _inv_sub_bytes(s)
        s = _ark(s, rks[r])
        s = _inv_mix_columns(s)
    s = _inv_shift_rows(s)
    s = _inv_sub_bytes(s)
    s = _ark(s, rks[0])
    return bytes(s)

